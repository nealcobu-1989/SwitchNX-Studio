"""Turns docs/manual.<lang>.md into app/web/manual.js, the Help page's content.

Run it after editing the manual:  python docs/build_manual.py
The test suite checks that manual.js is up to date and that both languages have
the same sections (the Help button opens a section by its id).

The Markdown is a small subset: "## Title {#id}" starts a section, "### " a
subheading; paragraphs; "- " and "1. " lists; tables; "> " for a tip; inline
`code`, **bold** and [text](#h-id) links (#page-<page> links open an app page).
"""
from __future__ import annotations

import html
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
LANGS = ("en", "es")
OUT = ROOT / "app" / "web" / "manual.js"

_SEC = re.compile(r"^##\s+(.+?)\s*\{#([a-z0-9-]+)\}\s*$")


def inline(text: str) -> str:
    codes: list[str] = []

    def keep(m):
        codes.append(f"<code>{html.escape(m.group(1), quote=False)}</code>")
        return f"\x00{len(codes) - 1}\x00"
    t = re.sub(r"`([^`]+)`", keep, text)
    t = html.escape(t, quote=False)
    t = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", t)

    def link(m):
        label, href = m.group(1), m.group(2)
        if not (href.startswith("#h-") or href.startswith("#page-") or href.startswith("https://")):
            raise ValueError(f"unsupported link target: {href}")
        return f'<a href="{html.escape(href)}">{label}</a>'
    t = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", link, t)
    return re.sub(r"\x00(\d+)\x00", lambda m: codes[int(m.group(1))], t)


def _cells(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def blocks(lines: list[str]) -> str:
    out: list[str] = []
    i = 0
    while i < len(lines):
        ln = lines[i]
        if not ln.strip():
            i += 1
            continue
        if ln.startswith("### "):
            out.append(f"<h3>{inline(ln[4:].strip())}</h3>")
            i += 1
        elif ln.startswith("|"):
            rows = []
            while i < len(lines) and lines[i].startswith("|"):
                rows.append(lines[i])
                i += 1
            head, body = _cells(rows[0]), [r for r in rows[1:] if not re.match(r"^\|\s*-", r)]
            t = "<table><thead><tr>" + "".join(f"<th>{inline(c)}</th>" for c in head) + "</tr></thead><tbody>"
            for r in body:
                cs = _cells(r)
                if len(cs) != len(head):
                    raise ValueError(f"table row has {len(cs)} cells, header has {len(head)}: {r}")
                t += "<tr>" + "".join(f"<td>{inline(c)}</td>" for c in cs) + "</tr>"
            out.append(t + "</tbody></table>")
        elif re.match(r"^(- |\d+\. )", ln):
            ordered = not ln.startswith("- ")
            items = []
            while i < len(lines) and re.match(r"^(- |\d+\. )", lines[i]):
                items.append(re.sub(r"^(- |\d+\. )", "", lines[i]).strip())
                i += 1
            tag = "ol" if ordered else "ul"
            out.append(f"<{tag}>" + "".join(f"<li>{inline(x)}</li>" for x in items) + f"</{tag}>")
        elif ln.startswith("> "):
            buf = []
            while i < len(lines) and lines[i].startswith("> "):
                buf.append(lines[i][2:].strip())
                i += 1
            out.append(f'<p class="tip">{inline(" ".join(buf))}</p>')
        else:
            buf = []
            while i < len(lines) and lines[i].strip() and not re.match(r"^(### |\||- |\d+\. |> )", lines[i]):
                buf.append(lines[i].strip())
                i += 1
            out.append(f"<p>{inline(' '.join(buf))}</p>")
    return "".join(out)


def sections(md: str) -> list[dict]:
    secs: list[dict] = []
    cur = None
    for ln in md.splitlines():
        m = _SEC.match(ln)
        if m:
            cur = {"id": m.group(2), "title": m.group(1), "lines": []}
            secs.append(cur)
        elif cur is not None:
            cur["lines"].append(ln)
    return [{"id": s["id"], "title": s["title"], "html": blocks(s["lines"])} for s in secs]


def build() -> str:
    data = {lang: sections((HERE / f"manual.{lang}.md").read_text(encoding="utf-8")) for lang in LANGS}
    ids = {lang: [s["id"] for s in data[lang]] for lang in LANGS}
    if ids["en"] != ids["es"]:
        raise ValueError(f"the languages have different sections: {ids}")
    body = json.dumps(data, ensure_ascii=False, indent=0)
    return ("// Generated by docs/build_manual.py from docs/manual.en.md and docs/manual.es.md. Don't edit by hand.\n"
            f"window.MANUAL = {body};\n")


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.read_text(encoding="utf-8") == text else 1)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(text)} bytes)")
